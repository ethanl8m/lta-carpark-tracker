// Helper to generate realistic 24h occupancy profiles for Singapore locations
function generateOccupancyTrend(peakType: 'office' | 'mall' | 'residential'): { hour: number; occupancyPercent: number }[] {
  const trends: { hour: number; occupancyPercent: number }[] = [];
  for (let hour = 0; hour < 24; hour++) {
    let rate = 20;
    if (peakType === 'office') {
      // Peaks 9am - 6pm on weekdays
      if (hour >= 8 && hour <= 18) {
        rate = 75 + Math.sin((hour - 8) / 10 * Math.PI) * 20;
      } else if (hour >= 19 && hour <= 21) {
        rate = 40;
      } else {
        rate = 15;
      }
    } else if (peakType === 'mall') {
      // Peaks 12pm - 2pm and 6pm - 9pm
      if (hour >= 11 && hour <= 14) {
        rate = 80 + Math.random() * 15;
      } else if (hour >= 17 && hour <= 21) {
        rate = 88 + Math.random() * 10;
      } else if (hour >= 22 || hour <= 9) {
        rate = 15 + Math.random() * 10;
      } else {
        rate = 50 + Math.random() * 15;
      }
    } else {
      // Residential HDB: High overnight & evening, lower midday
      if (hour >= 20 || hour <= 7) {
        rate = 85 + Math.random() * 10;
      } else if (hour >= 10 && hour <= 16) {
        rate = 35 + Math.random() * 15;
      } else {
        rate = 60 + Math.random() * 15;
      }
    }
    trends.push({ hour, occupancyPercent: Math.min(100, Math.max(5, Math.round(rate))) });
  }
  return trends;
}

